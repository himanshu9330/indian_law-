"""
Export utilities for LexAI conversations and answers.
Provides:
  - Markdown export
  - Clean, encoding-safe PDF export using fpdf2 (with disclaimer, risk badge, citations, roadmap)
"""

from datetime import datetime, timezone
from io import BytesIO
import re
from typing import Any, Optional


def export_markdown(
    chat_title: str,
    messages: list[dict],
    created_at: Optional[str] = None,
) -> str:
    """Generate a clean Markdown document of a chat conversation."""
    lines = [
        f"# ⚖️ LexAI Legal Consultation: {chat_title}",
        f"**Date**: {datetime.now(timezone.utc).strftime('%B %d, %Y %I:%M %p UTC')}",
        "",
        "> ⚠️ **IMPORTANT DISCLAIMER**: The information provided below is generated by LexAI, "
        "an AI-powered assistant for Indian law, and is for general educational and informational purposes only. "
        "It does not constitute formal legal advice or create an attorney-client relationship. "
        "Always consult an enrolled advocate for matters affecting your legal rights.",
        "",
        "---",
        "",
    ]

    for i, msg in enumerate(messages, 1):
        role = msg.get("role", "user")
        content = msg.get("content", "")
        meta = msg.get("metadata", {}) or {}

        if role == "user":
            lines.append(f"## 👤 User Query\n\n{content}\n")
        elif role == "assistant":
            risk = meta.get("risk", "").upper()
            source = meta.get("source", "KNOWLEDGE BASE")
            score = meta.get("confidence_score")
            score_str = f" | Confidence: {score}" if score is not None else ""

            lines.append(f"## ⚖️ LexAI Legal Guidance")
            if risk:
                lines.append(f"**Risk Level**: `{risk}` | **Source**: `{source}`{score_str}\n")
            lines.append(content)
            lines.append("\n---\n")

    lines.append("\n*Generated by LexAI — AI-Powered Legal Assistant for Indian Law.*")
    return "\n".join(lines)


def _clean_pdf_text(text: str) -> str:
    """
    Sanitize text to safe Latin-1 for standard PDF core fonts (Helvetica).
    Replaces unicode symbols, currency signs, and emojis with text equivalents
    to prevent FPDFUnicodeEncodingException.
    """
    if not text:
        return ""

    replacements = {
        "—": " - ",
        "–": " - ",
        "―": " - ",
        "₹": "Rs. ",
        "•": "* ",
        "“": '"',
        "”": '"',
        "‘": "'",
        "’": "'",
        "…": "...",
        "➔": " -> ",
        "→": " -> ",
        "§": "Sec. ",
        "⚖️": "",
        "⚖": "",
        "👤": "",
        "🚨": "[!]",
        "📌": "*",
        "📍": "*",
        "🗑️": "",
        "👍": "[+1]",
        "👎": "[-1]",
        "⭐": "[*]",
        "🔖": "[Saved]",
        "📄": "[Doc]",
        "📑": "[PDF]",
        "💡": "[Tip]",
        "✅": "[OK]",
        "⏳": "[...]",
        "🎉": "",
        "🇮🇳": "",
        "⚡": "",
        "📚": "",
        "🌐": "",
        "🔒": "",
        "🧠": "",
        "🏛️": "",
        "🏛": "",
        "🗺️": "",
        "🛡️": "",
    }
    for k, v in replacements.items():
        text = text.replace(k, v)

    # Encode to latin-1, ignoring any unsupported characters (e.g. Devanagari, emojis)
    return text.encode("latin-1", "ignore").decode("latin-1")


def export_pdf(
    chat_title: str,
    messages: list[dict],
) -> bytes:
    """
    Generate a branded PDF document of the consultation using fpdf2.
    Safe against unicode encoding exceptions. Returns bytes for download_button.
    """
    try:
        from fpdf import FPDF
    except ImportError:
        # Fallback if fpdf2 is somehow missing
        return b"%PDF-1.4 Empty PDF (fpdf2 not installed)"

    try:
        class LegalPDF(FPDF):
            def header(self):
                self.set_font("Helvetica", "B", 13)
                self.set_text_color(26, 32, 44)  # Deep navy
                # Clean ASCII/Latin-1 title
                self.cell(0, 8, "LexAI - Indian Legal Consultation Report", border=0, ln=1, align="L")
                self.set_font("Helvetica", "", 8)
                self.set_text_color(113, 128, 150)
                self.cell(
                    0,
                    4,
                    f"Confidential & Informational - Generated on {datetime.now().strftime('%d %b %Y')}",
                    border=0,
                    ln=1,
                    align="L",
                )
                self.line(10, 24, 200, 24)
                self.ln(6)

            def footer(self):
                self.set_y(-15)
                self.set_font("Helvetica", "I", 8)
                self.set_text_color(160, 174, 192)
                self.cell(
                    0,
                    10,
                    f"Page {self.page_no()} | LexAI does not provide formal legal advice. Consult an enrolled advocate.",
                    align="C",
                )

        pdf = LegalPDF()
        pdf.set_auto_page_break(auto=True, margin=18)
        pdf.add_page()

        # Title
        pdf.set_font("Helvetica", "B", 15)
        pdf.set_text_color(26, 54, 93)  # Rich navy
        safe_title = _clean_pdf_text(chat_title) or "Legal Consultation"
        pdf.multi_cell(0, 8, safe_title)
        pdf.ln(3)

        # Disclaimer Box
        pdf.set_fill_color(254, 243, 199)  # Warm amber
        pdf.set_draw_color(217, 119, 6)
        pdf.set_font("Helvetica", "B", 8)
        pdf.set_text_color(146, 64, 14)
        pdf.cell(0, 5, "LEGAL DISCLAIMER", ln=1, fill=True)
        pdf.set_font("Helvetica", "", 8)
        disclaimer_text = (
            "This consultation report is generated by an artificial intelligence tool for educational and general "
            "guidance under Indian law. It does not constitute formal legal counsel. For actionable legal steps, "
            "court appearances, or binding opinions, please engage a licensed advocate enrolled with the Bar Council."
        )
        pdf.multi_cell(0, 4, disclaimer_text, fill=True)
        pdf.ln(6)

        # Messages
        for msg in messages:
            role = msg.get("role", "user")
            content = msg.get("content", "")
            meta = msg.get("metadata", {}) or {}

            if role == "user":
                pdf.set_font("Helvetica", "B", 11)
                pdf.set_text_color(43, 108, 176)
                pdf.cell(0, 6, "User Query:", ln=1)
                pdf.set_font("Helvetica", "", 9)
                pdf.set_text_color(45, 55, 72)
                safe_content = _clean_pdf_text(content)
                pdf.multi_cell(0, 5, safe_content)
                pdf.ln(4)

            elif role == "assistant":
                risk = meta.get("risk", "low").upper()
                source = meta.get("source", "KNOWLEDGE BASE")
                confidence = meta.get("confidence_score")

                pdf.set_font("Helvetica", "B", 11)
                pdf.set_text_color(26, 32, 44)
                pdf.cell(0, 6, "LexAI Legal Guidance:", ln=1)

                # Metadata badge line
                pdf.set_font("Helvetica", "I", 8)
                pdf.set_text_color(113, 128, 150)
                meta_line = f"Risk: {risk}  |  Source: {source}"
                if confidence is not None:
                    meta_line += f"  |  Confidence Score: {confidence}"
                pdf.cell(0, 4, _clean_pdf_text(meta_line), ln=1)
                pdf.ln(2)

                # Body text
                pdf.set_font("Helvetica", "", 9)
                pdf.set_text_color(45, 55, 72)
                safe_content = _clean_pdf_text(content)
                pdf.multi_cell(0, 5, safe_content)
                pdf.ln(5)

                pdf.set_draw_color(226, 232, 240)
                pdf.line(10, pdf.get_y(), 200, pdf.get_y())
                pdf.ln(4)

        return bytes(pdf.output())
    except Exception as e:
        print(f"Error generating PDF: {e}")
        # Return a valid fallback PDF
        return b"%PDF-1.4\n1 0 obj<</Type/Catalog/Pages 2 0 R>>endobj 2 0 obj<</Type/Pages/Kids[3 0 R]/Count 1>>endobj 3 0 obj<</Type/Page/MediaBox[0 0 612 792]/Parent 2 0 R/Resources<<>>>>endobj\nxref\n0 4\n0000000000 65535 f\n0000000010 00000 n\n0000000053 00000 n\n0000000102 00000 n\ntrailer<</Size 4/Root 1 0 R>>\nstartxref\n178\n%%EOF"
