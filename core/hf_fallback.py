def generate_indian_legal_fallback(
    query: str,
    refined_query: Optional[str] = None,
    risk: str = "medium",
    style: str = "detailed",
    fallback_reason: str = "Pinecone retrieval confidence below threshold",
    openrouter_api_key: Optional[str] = None,
    openrouter_model: Optional[str] = None,
    hf_api_key: Optional[str] = None,
    hf_model: Optional[str] = None,
) -> dict[str, Any]:
    """
    Main fallback answer generation engine.
    Orchestrates OpenRouter (Qwen) -> Hugging Face -> Groq Qwen -> Safe Grounded Indian Synthesis.
    """
    refined = refined_query or query
    style_inst = STYLE_SIMPLE if style == "simple" else STYLE_DETAILED
    detail_lvl = "plain-language, easy-to-understand" if style == "simple" else "rigorous, statutory"

    prompt = INDIAN_LEGAL_FALLBACK_PROMPT.format(
        query=query,
        refined_query=refined,
        risk=risk.upper(),
        style_instruction=style_inst,
        detail_level=detail_lvl,
    )
    system_prompt = "You are a specialized Indian Legal AI Assistant fine-tuned on the Constitution, BNS 2024, BNSS 2024, and Indian civil law."

    raw_answer: Optional[str] = None
    engine_used = "offline_grounded_fallback"

    # 1. Try OpenRouter Qwen
    or_key = _clean_str(openrouter_api_key or OPENROUTER_API_KEY)
    or_model = _clean_str(openrouter_model or OPENROUTER_MODEL or "qwen/qwen-2.5-72b-instruct")
    if or_key:
        raw_answer = _call_openrouter_api(
            prompt=prompt,
            system_prompt=system_prompt,
            model=or_model,
            api_key=or_key,
        )
        if raw_answer:
            engine_used = f"openrouter/{or_model}"

    # 2. Try Hugging Face Inference API
    if not raw_answer:
        hf_key = _clean_str(hf_api_key or HUGGINGFACE_API_KEY)
        hf_m = _clean_str(hf_model or HUGGINGFACE_MODEL or "law-ai/InLegalBERT")
        if hf_key:
            raw_answer = _call_huggingface_api(
                prompt=f"{system_prompt}\n\n{prompt}",
                model=hf_m,
                api_key=hf_key,
            )
            if raw_answer:
                engine_used = f"huggingface/{hf_m}"

    # 3. Try Groq Qwen
    if not raw_answer:
        raw_answer = _call_groq_fallback(prompt=prompt, system_prompt=system_prompt)
        if raw_answer:
            engine_used = "groq/qwen3.8-27b"

    # 4. Safe Grounded Synthesis
    if not raw_answer:
        raw_answer = _generate_grounded_fallback(
            query=query,
            refined_query=refined,
            risk=risk,
            reason=fallback_reason,
        )
        engine_used = "local_grounded_synthesis"

    structured = parse_structured_answer(raw_answer)

    return {
        "raw_answer": raw_answer,
        "structured_sections": structured,
        "answer_source": "huggingface_fallback",
        "engine_used": engine_used,
        "fallback_reason": fallback_reason,
        "response_status": "success",
    }

