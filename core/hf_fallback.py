def _clean_str(val: Optional[str]) -> str:
    """Sanitize string values."""
    return (val or "").strip().strip("\"' ")


def _call_openrouter_api(
    prompt: str,
    system_prompt: str,
    model: str,
    api_key: str,
    temperature: float = 0.2,
) -> Optional[str]:
    """Call OpenRouter Chat Completion API for Qwen models."""
    clean_key = _clean_str(api_key)
    if not clean_key:
        return None

    # Intelligent Guardrail: If model is set to a TTS model (e.g. qwen3-tts-1.7b),
    # route text reasoning to Qwen 2.5 Instruct to prevent 400 Bad Request
    active_model = model.strip()
    if "tts" in active_model.lower():
        logger.info("Routing text legal generation from TTS model to qwen/qwen-2.5-72b-instruct")
        active_model = "qwen/qwen-2.5-72b-instruct"

    url = "https://openrouter.ai/api/v1/chat/completions"
    headers = {
        "Authorization": f"Bearer {clean_key}",
        "Content-Type": "application/json",
        "HTTP-Referer": "https://lexai.bharat.local",
        "X-Title": "LexAI Bharat Legal Assistant",
        "User-Agent": "LexAI-IndianLaw/2.0",
    }

    payload = json.dumps({
        "model": active_model,
        "messages": [
            {"role": "system", "content": system_prompt},
            {"role": "user", "content": prompt},
        ],
        "temperature": temperature,
        "max_tokens": 1800,
    }).encode("utf-8")

    req = urllib.request.Request(url, data=payload, headers=headers, method="POST")
    try:
        with urllib.request.urlopen(req, timeout=25) as response:
            if response.status == 200:
                data = json.loads(response.read().decode("utf-8"))
                choices = data.get("choices", [])
                if choices and "message" in choices[0]:
                    content = choices[0]["message"].get("content", "").strip()
                    if content:
                        return content
    except Exception as e:
        logger.warning("OpenRouter API call failed (%s): %s", active_model, e)
    return None


def _call_huggingface_api(
    prompt: str,
    model: str,
    api_key: str,
) -> Optional[str]:
    """Call Hugging Face Inference API."""
    clean_key = _clean_str(api_key)
    if not clean_key:
        return None

    url = f"https://api-inference.huggingface.co/models/{model}"
    headers = {
        "Authorization": f"Bearer {clean_key}",
        "Content-Type": "application/json",
        "User-Agent": "LexAI-IndianLaw/2.0",
    }
    payload = json.dumps({
        "inputs": prompt,
        "parameters": {"max_new_tokens": 1024, "temperature": 0.2, "return_full_text": False},
    }).encode("utf-8")

    req = urllib.request.Request(url, data=payload, headers=headers, method="POST")
    try:
        with urllib.request.urlopen(req, timeout=20) as response:
            if response.status == 200:
                data = json.loads(response.read().decode("utf-8"))
                if isinstance(data, list) and len(data) > 0:
                    return data[0].get("generated_text", "")
                if isinstance(data, dict):
                    return data.get("generated_text", "")
    except Exception as e:
        logger.warning("Hugging Face API call failed (%s): %s", model, e)
    return None


def _call_groq_fallback(prompt: str, system_prompt: str) -> Optional[str]:
    """Call Groq Qwen as alternative high-speed fallback."""
    clean_groq = (os.getenv("GROQ_API_KEY") or GROQ_API_KEY or "").strip().strip("\"' ")
    if not clean_groq or clean_groq in ("", "your_groq_api_key_here"):
        return None
    from core.llm import call_llm
    try:
        res = call_llm(
            prompt=prompt,
            system_prompt=system_prompt,
            temperature=0.2,
            model="qwen/qwen3.8-27b",
            api_key=clean_groq,
        )
        if res and len(res.strip()) > 50 and "Demo Mode" not in res and "configured" not in res and "Error" not in res:
            return res
    except Exception as e:
        logger.warning("Groq Qwen fallback failed: %s", e)
    return None


